/*
给你一个整数 n，表示一棵有 n 个节点的树，节点编号从 0 到 n - 1，并且树以节点 0 为 根节点。这棵树由一个长度为 n - 1 的二维数组 edges 表示，其中 edges[i] = [ui, vi] 表示节点 ui 和 vi 之间存在一条 无向 边。

另给你一个长度为 n 的字符串 colors，其中 colors[i] 表示节点 i 的颜色：'R' 表示红色，'B' 表示蓝色。

你可以 翻转 任意节点的颜色：从 'R' 变为 'B'，或从 'B' 变为 'R'。翻转节点 u 的代价等于以节点 u 为根的子树的大小。

你的目标是通过翻转颜色，使所有 红色 节点在树中形成 一个连通分量 。蓝色节点可以不连通。没有红色节点的配置也视为有效。

返回实现这一目标所需的 最小总代价 。
1 <= n <= 1e5
n == colors.length
colors[i] 为 'R' 或 'B'。
edges.length == n - 1
edges[i] = [ui, vi]
0 <= ui, vi <= n - 1
输入保证 edges 表示一棵有效的树。
[thinking]
我们先把所有的节点都变成蓝色（代价最大）。
此时，需要翻转所有红色节点。
设每个节点的子树大小为 size[x]。
那么把全变蓝的总代价记作 base，base = 所有红色节点的 size 之和。
现在我们想从“全蓝”的状态往回退，重新把一些节点变红。为了让代价最小，我们要尽量减少 base。

对于原本就是红色的节点
x
x：如果我们把它保留红色（不让它变蓝），我们就省下了 size[x] 的代价。相当于我们赚了 size[x]。

对于原本是蓝色的节点
x
x：如果我们把它变成红色，我们需要额外花费 size[x] 的代价。相当于我们亏了 size[x]。

所以，我们给每个节点赋予一个权重（收益） a[x]：
**树上如果选一片连通的区域一起变红，很多翻转操作可以互相抵消，不用单独一个个翻，能省钱**。
也就是：我们不用花满 base，能省下一部分代价。
我们定义：我们最终选定的连通块 S（就是最后留下来是红色的节点集合）

- 节点本来就是红色：
如果它放进 S（保留红，不用去翻转它），那原本要花的 size [x] 不用花了 → **赚 size [x]**，`a[x]=+size[x]`
- 节点本来是蓝色：
如果硬把它放进 S（强行变红），那要多付出 size [x] 的代价 → **亏 size [x]**，`a[x]=-size[x]`
- 红节点进 S：代价 ↓size [x]，收益 + size [x]
- 蓝节点进 S：代价 ↑size [x]，收益 - size [x]
如果是红节点：a[x] = size[x] (正数，赚的)

如果是蓝节点：a[x] = -size[x] (负数，亏的)

现在的目标变成了：
base 的含义：**如果我们不做任何 “合并抵消”，单独把每一个红点都翻出来，要花的最大代价**。
在树上找一个连通块（把这些节点都变成红色），使得这个连通块的总收益最大（点权之和最大）。
找到了最大收益 max_profit，最终答案就是：base - max_profit。
总代价 - 最大省钱 = 最小代价
*/
// 树形DP
/*
树形 DP 的精髓是：从下往上，逐层汇报。

假设节点 x 是老板，它下面有若干员工（子节点 y）。
老板要组建一个连通块，前提是老板自己必须先加入。

老板 x 问底下所有员工 y：“如果你们跟我干（以你为根的子树），最多能带来多少收益？”
员工 y 经过计算，汇报一个数字 f[y]。

老板 x 拿到所有员工的汇报后开始决策：
如果员工 y 的汇报 f[y] > 0（能赚钱），老板就带上这个员工，收益加上 f[y]；
如果员工 y 的汇报 f[y] < 0（会亏钱），老板就不选这一段子树，收益加 0。

于是老板 x 的总收益公式：
f[x] = a[x] + sum(max(f[y], 0))

f[x] 的含义：必须选 x 的前提下，以 x 为根的子树里能拿到的最大收益。
*/
package main

func minCost(n int, colors string, edges [][]int) int64 {
	// 1. 建图（常规操作，为了方便找儿子）
	g := make([][]int, n)
	for _, e := range edges {
		x, y := e[0], e[1]
		g[x] = append(g[x], y)
		g[y] = append(g[y], x)
	}

	base, mx := 0, 0 // base是总代价，mx是记录全树最大连通块收益

	// dfs(x, fa) 意思是：计算节点 x 的 size，以及在必定选 x 的情况下的最大收益 f
	//`f`：**是的，f [x] 就是我们前面说的：必须选 x 的前提下，以 x 为根子树的连通块最大收益**
	var dfs func(int, int) (int, int)
	dfs = func(x, fa int) (int, int) {
		size := 1 // 子树初始大小为1（自己）
		f := 0    // DP状态f[x]，初始先为0，后面再加自己的a[x]

		// 遍历所有邻接点
		for _, y := range g[x] {
			if y != fa { // y不是爸爸 → y是儿子
				sz, fy := dfs(y, x) // 递归儿子：拿到儿子的size，儿子的f[y]
				size += sz          // 累加子树大小，往上回传
				f += max(fy, 0)     // ✨老板决策：儿子fy>0就带上，<=0就不加
			}
		}

		// ========= 给x加上自己的点权 a[x] =========
		if colors[x] == 'R' {
			base += size // x是原始红点：笨方案要花size把它翻蓝，计入base
			f += size    // a[x]=+size：把x放进S（变红），省下size，收益+size
		} else {
			f -= size // a[x]=-size：x原本蓝色，放进S强行变红，亏size，收益-size
		}

		mx = max(mx, f)
		// 更新全局最大收益：x这个连通块（必选x）的收益，有可能是全局最优S
		return size, f
	}

	dfs(0, -1) // 从根节点0开始，-1代表没有父节点

	// 最终答案：全变蓝的代价 - 最大的收益
	// 为什么要和0取max？因为题目说“没有红节点（全蓝）也是合法的”，如果选红节点全在亏钱，不如全变蓝。
	return int64(base - max(mx, 0))
}
