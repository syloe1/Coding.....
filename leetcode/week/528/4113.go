/*
Alice 和 Bob 正在用一个整数数组 nums 玩游戏。Alice 先手。
每个回合，当前玩家可以取走并移除 最左边的一个元素 ，或者在至少还剩两个元素时，取走并移除 最左边的两个元素。
本回合取走的元素之 和 决定接下来由谁行动：
如果该总和能被 3 整除，则接下来由另一位玩家行动。
否则，当前玩家继续行动。
一位玩家的 得分 是其取走的所有元素的值之和。
两位玩家都采用最优策略，各自力求 最大化 自己的得分。
当所有元素都被取走时，游戏结束。
返回 Alice 的得分 减去 Bob 的得分。
n <= 1e5 val < 1e9
*/
/*
定义 dp[i] 表示：当数组只剩下 nums[i:] 时，当前行动者相对于另一位玩家能够获得的最大分差。
即： dp[i] = 当前行动者得分 - 另一位玩家得分
当前玩家每次可以选择取走最左边的一个元素，或者取走最左边的两个元素。
设本次取走的元素之和为 s，剩余数组从 i+k 开始，其中 k 为本次取走的元素个数。
根据 s 是否能被 3 整除，分为两种情况：
情况一：s 不能被 3 整除
下一回合仍然由当前玩家行动。
因此，后续的最大分差仍然是从当前玩家的视角计算的，直接加上后续状态：
dp[i] = s + dp[i+k]
情况二：s 能被 3 整除
下一回合切换为另一位玩家。
此时，后续状态 dp[i+k] 是从对手的视角计算的，因此需要取反：
dp[i] = s - dp[i+k]
每个位置有两种选择：
取走一个元素：s = nums[i]，后续状态为 dp[i+1]。
取走两个元素：s = nums[i] + nums[i+1]，后续状态为 dp[i+2]，但必须保证 i+1 < n。
当前玩家会选择使自己最终分差最
dp[i] = max(取一个元素的结果, 取两个元素的结果)大的方案，因此：
*/
func maxDifference(nums []int) int64 {
	n := len(nums)
	dp := make([]int64, n+2)
	for i := n - 1; i >= 0; i-- {
		s := int64(nums[i])
		if s%3 == 0 {
			// 玩家已经取得s分， 下把游戏从  i + 1 开始 dp[i+1]
			//alice 拿到3分， 下一轮bob拿10分，alice拿6分，
			//分差就是 dp[i+1] = 10 - 6 = 4
			dp[i] = s - dp[i+1]
		} else {
			dp[i] = s + dp[i+1] //同一个人
		}
		if i+1 < n {
			s += int64(nums[i+1])
			var v int64
			if s%3 == 0 {
				v = s - dp[i+2]
			} else {

				v = s + dp[i+2]
			}
			dp[i] = max(dp[i], v)
		}
	}
	return dp[0]
}