/*
题目描述
小蓝正在数轴上挖矿，数轴上一共有 n 个矿洞，第 i 个矿洞的坐标为 ai 。小蓝从 0 出发，每次可以向左或向右移动 1 的距离，当路过一个矿洞时，就会进行挖矿作业，获得 1 单位矿石，但一个矿洞不能被多次挖掘。小蓝想知道在移动距离不超过 m 的前提下，最多能获得多少单位矿石？
输入格式
输入的第一行包含两个正整数 n, m ，用一个空格分隔。第二行包含 n 个整数 a1, a2, · · · , an ，相邻整数之间使用一个空格分隔。
输出格式
输出一行包含一个整数表示答案。

矿洞在数轴上，起点 0；
规则：

- 走过矿洞就挖掉，一个只能挖一次
- 总移动距离 ≤ m
- 求最多挖多少矿

👉 最优路径一定是：**先往一个方向走到端点，再折返到另一边的端点**
比如：向左走到 L，再向右走到 R；或者向右走到 R，再向左走到 L。
区间 `[L, R]` 里面所有矿都能挖到。
设：

- `l`：最左点（负数），距离原点 `left = -l`
- `r`：最右点（正数），距离原点 `right = r`
总路程两种情况：

1. 先左后右：`2*left + right`
2. 先右后左：`2*right + left`
只要其中一个 ≤ m，这个区间内所有矿都可取。

把所有矿洞坐标从小到大排序之后：
✅ 能一起挖到的矿，一定是排序后**连续的一整段** `a[l] ~ a[r]`

>
> 为什么？假设你选了 -1,0,2，跳过了 1。那你走到 - 1 折返到 2 的时候，**1 本来就在路上，顺路就挖了，不可能故意跳过**。
> 所以最优解一定是排序数组里连续窗口。这个是贪心根基。

窗口里：

- 最左点：`L = a[l]`（≤0，负数或者 0）
- 最右点：`R = a[r]`（≥0，正数或者 0）

>
> 如果窗口全在右边（L≥0）：不用往左走，直接走到 R，代价就是 R
> 如果窗口全在左边（R≤0）：不用往右走，代价就是 -L
> 如果窗口横跨 0（L<0，R>0）：两种走法
>
>
> 1. 先去左边 L，折返回来再走到 R：路程 = `2*(-L) + R`
> 2. 先去右边 R，折返回来再走到 L：路程 = `2*R + (-L)`
> 只要两种走法里**最小的那个 ≤ m**，这个窗口就合法！
数组已经升序排序，我们找最长窗口 `[l, r]`，满足上面的代价条件。
双指针原理：

- r 慢慢向右扩大窗口（尝试多拿矿）
- 如果当前窗口代价超标了，就把 l 往右缩（丢掉最左边的矿）
- 每一轮 r 固定的时候，l 只会往右走，不会回头 → O (n)
*/
package main

import (
	"fmt"
	"sort"
)

func ok(L, R, m int) bool {
	if R <= 0 {
		return -L <= m
	}
	if L >= 0 {
		return R <= m
	}
	c1 := 2*(-L) + R // 先左后右
	c2 := 2*R + (-L) //先右后左
	return c1 <= m || c2 <= m
}
func main() {
	var n, m int
	fmt.Scan(&n, &m)
	a := make([]int, n)
	for i := 0; i < n; i++ {
		fmt.Scan(&a[i])
	}
	sort.Ints(a)
	l := 0
	ans := 0
	for r := 0; r < n; r++ {
		for l <= r && !ok(a[l], a[r], m) {
			l++
		}
		if l <= r {
			if r-l+1 > ans {
				ans = r - l + 1
			}
		}
	}
	fmt.Println(ans)
}
