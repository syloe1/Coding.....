/*
题目 3351: 蓝桥杯2026年第十七届省赛真题-循环右移 时间限制: 1s 内存限制: 128MB
题目描述
给定三个整数 N, X, Y。请计算有多少个长度为 N 的整数数组 A 满足以下条件:
1. 数组 A 中的每个元素 Ai 都满足 X ≤ Ai ≤ Y;
2. 对于数组 A 中的任意一个连续子数组，对其进行一次循环右移操作，得到的新子数组与原数组完全一致。
循环右移: 对一个长度为 k 的连续子数组 [B1, B2,…, Bk] 执行一次循环右移操作，是指将该子数组变换为 [Bk, B1, B2,…, Bk−1] (即把最后一个元素移到最开头，其余元素保持原有顺序依次向后顺延一位)。
输入格式
第一行包含一个整数 T，表示测试数据的组数。
接下来的 T 行，每行包含三个由空格隔开的整数 N, X, Y。
输出格式
对于每组测试数据，输出一行，包含一个整数，表示满足条件的数组 A 的个数。
样例输入
3
3 1 2
5 10 10
2 5 3
样例输出
2
1
0
提示
对于 30% 的评测用例，1 ≤ T ≤ 20，1 ≤ N ≤ 100，1 ≤ X,Y ≤ 100;
对于 100% 的评测用例，1 ≤ T ≤ 10³，1 ≤ N ≤ 10¹⁸，1 ≤ X,Y ≤ 10¹⁸。

*/
/*
合法数组必须是一个所有元素都相等的数组。

反过来，如果所有元素都相等，那么无论选择哪个连续子数组，循环右移后肯定还是原来的样子。
原题要求：
- 数组长度为 N。
- 每个元素满足 val in [X, Y]
- 所有元素必须相等。

*/
package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	in := bufio.NewReader(os.Stdin)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()

	var t int
	fmt.Fscan(in, &t)

	for ; t > 0; t-- {
		var n, x, y int64
		fmt.Fscan(in, &n, &x, &y)
		if x > y {
			fmt.Fprintln(out, 0)
		} else {
			fmt.Fprintln(out, y-x+1)
		}
	}

}
