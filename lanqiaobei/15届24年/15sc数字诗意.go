/*
在诗人的眼中，数字是生活的韵律，也是诗意的表达。

小蓝，当代顶级诗人与数学家，被赋予了 “数学诗人” 的美誉。他擅长将冰冷的数字与抽象的诗意相融合，并用优雅的文字将数学之美展现于纸上。

某日，小蓝静坐书桌前，目光所及，展现着 n 个数字，它们依次为a1, a2, . . . , an，熠熠生辉。小蓝悟到，如果一个数能够以若干个（至少两个）连续的正整数相加表示，那么它就蕴含诗意。例如，数字 6 就蕴含诗意，因为它可以表示为 1 + 2 + 3。而 8 则缺乏诗意，因为它无法用连续的正整数相加表示。

小蓝希望他面前的所有数字都蕴含诗意，为此，他决定从这 n 个数字中删除一部分。请问，小蓝需要删除多少个数字，才能使剩下的数字全部蕴含诗意？

输入格式
输入的第一行包含一个整数 n，表示展示的数字个数。

第二行包含 n 个整数 a1, a2, . . . , an，相邻整数之间使用一个空格分隔，表示展示的数字。

输出格式
输出一行包含一个整数，表示小蓝需要删除的数字个数，以使剩下的数字全部蕴含诗意。
*/
/*
一个正整数 x 可以写成至少两个连续正整数之和 ⇔ x 不是 2 的整数次幂
核心判定：判断 x 是否是 2 的幂。
判断方法：x > 0 && (x & (x - 1)) == 0
⚠️ 注意：a_i 可以到 10^16，要用 64 位整数（C++ unsigned long long /long long，Go uint64）
k 个连续正整数，首项 a，k ≥ 2

S = a + (a+1) + … + (a+k-1) = k·(2a + k - 1) / 2
2S = k · (2a + k - 1)
约束：

- a ≥ 1 → 2a +k -1 ≥ k+1
- k ≥ 2
- k 和 (2a+k-1)：奇偶一定不同
理由：2a+k-1 -k = 2a-1，差是奇数 → 一奇一偶

翻译：2S 必须能拆成两个大于 1 的正整数相乘，且一奇一偶。
*/
package main

import (
	"bufio"
	"fmt"
	"os"
)

func isPow2(x uint64) bool {
	return x > 0 && (x&(x-1)) == 0
}

func main() {
	in := bufio.NewReader(os.Stdin)
	var n int
	fmt.Fscan(in, &n)
	ans := 0
	for i := 0; i < n; i++ {
		var x uint64
		fmt.Fscan(in, &x)
		if isPow2(x) {
			ans++
		}
	}
	fmt.Println(ans)
}
