/*
D 喧嚣
题意：
n个人，k次进攻，每次在x发起进攻。
x得颜色1，x+1颜色2 … min(n,x+m‑1)颜色m。
一个人集齐全部m种颜色，受伤一次，清空所有标记。求每个人受伤次数。

关键数学转换：
对于位置pos，想要给他颜色c，进攻发起位置必须 x = pos‑c+1。
c取1~m，对应发起位置 pos, pos‑1 … pos‑m+1。
cnt[x]：发起位置x的进攻总次数。
pos受伤次数 = min{ cnt[pos‑m+1], cnt[pos‑m+2], ... , cnt[pos] }
若pos‑m+1 < 1，则越界部分值为0，min直接得到0。

问题等价：数组cnt，求大小为m的滑动窗口最小值。
样例：
n=6 m=3
cnt = [1,2,1,2,1,3]
pos3窗口[1,2,3] min(1,2,1)=1
pos4窗口[2,3,4] min(2,1,2)=1
输出0 0 1 1 1 1

算法：
1.统计cnt频率数组 O(k)
2.单调队列求滑动窗口最小值 O(n)
边界：窗口左端点小于1，对应数值为0。
答案就是窗口最小值。

*/