/*
什么情况下连通点对数最多？
总点对数是固定的 C(n,2)。要求 k 个连通块，为了让连通点对最多，我们要让某个连通块尽可能大（把大部分点装进去），剩下的 k−1 个连通块每个只包含 1 个孤立的点。
因此，最优的连通块结构是：
1 个大小为 n−k+1 的大连通块
k−1 个大小为 1 的孤立点
判断是否合法（无解情况）：
设大连通块的节点数为 S = n−k+1。
要让这 S 个点连通，最少需要 S−1 = n−k 条边（也就是一棵树）。
要让这 S 个点之间的连通点对最多，最多可以连成一个完全图，需要的边数为 S×(S−1)/2。
因此，如果 m < n−k 或者 m > S×(S−1)/2，说明边太少连不通，或者边太多会发生重边/自环，直接输出 -1。

如何构造？
既然前 S 个点必须连通，我们可以直接枚举前 S 个点的所有点对 (u,v)（1≤u<v≤S），只要没达到 m 条边，就把它们连起来。
因为 S 个点的完全图边数是足够的，而且任意连边都不会破坏这 S 个点的连通性。
剩下的 k−1 个点（编号 S+1 到 n）不连任何边，它们自然形成 k−1 个独立的连通块。
*/
package main

import (
	"bufio"
	"fmt"
	"os"
)

func main() {
	in := bufio.NewReader(os.Stdin)
	out := bufio.NewWriter(os.Stdout)
	defer out.Flush()
	var t int
	fmt.Fscan(in, &t)
	for ; t > 0; t-- {
		var n, m, k int
		fmt.Fscan(in, &n, &m, &k)

		// 最大连通块的节点数
		s := n - k + 1
		mi := n - k           //树
		ma := s * (s - 1) / 2 //完全图
		if m < mi || m > ma {
			fmt.Fprintln(out, -1)
			continue
		}
		c := 0
		for u := 1; u <= s && c < m; u++ {
			for v := u + 1; v <= s && c < m; v++ {
				fmt.Fprintln(out, u, v)
				c++
			}
		}
	}
}
