/*
每件物品**只能选一次**，选 or 不选，二选一；这就是「01」的由来。
前置：动态规划，最优子结构、无后效性。
有一个背包，容量是 V；
一共有 n 个物品：
物品 i：重量 \(w[i]\)，价值 \(v[i]\)
每个物品最多拿 1 个。
求：背包不超重前提下，能装的**最大总价值**。

设 `dp[i][j]` = 只考虑前 `i` 个物品，背包容量为 `j` 时，可以拿到的最大价值。
	不选第i件物品 dp[i][j] = dp[i-1][j]
	选第i件物品 j >= w[i]  dp[i][j] = dp[i-1][j-w[i]] + v[i]
初始条件
	dp[0][j] = 0. 0 个物品，不管多大背包，价值都是 0
	dp[i][0] = 0. 背包容量 0，啥都装不下，价值 0
*/
// 01背包二维
// n:物品数量, V:背包容量
// w[]:物品重量, v[]:物品价值，下标从1开始对齐dp
// 返回最大价值
package main

func TwoDim01(n, V int, w, v []int) int {
	// dp[i][j]：前i个物品，容量j的最大价值
	dp := make([][]int, n+1)
	for i := range dp {
		// return dp[n][V]
		dp[i] = make([]int, V+1)
	}
	// 枚举物品
	for i := 1; i <= n; i++ {
		for j := 1; j <= V; j++ {
			if j < w[i] {
				// 放不下第i个物品
				dp[i][j] = dp[i-1][j]
			} else {
				dp[i][j] = max(dp[i-1][j], dp[i-1][j-w[i]]+v[i])
			}
		}
	}
	return dp[n][V]
}

/*
优化成1维
dp[j]   = max(dp[j], dp[j-w[i]] + v[i])
     这里右边的 `dp[j]` 和 `dp[j-w[i]]`，**都必须是 i-1 的旧值**，不能是本轮 i 刚改出来的新值。
	 j - w[i] < j, 先算小的 j，把 `dp[j-w[i]]` 改成新值了；后面更大的 j 去读的时候，读到的是本轮 i 新算出来的值 → 相当于这个物品可以反复拿。
	 如果 **逆序 j：从大到小（V downto w [i]）**
j 是往变小的方向走；`j-w[i]` 比 j 更小，**还没轮到本轮修改它，它保留的是 i-1 的旧状态**！✅
这个数组在处理第i个物品之前，存的是i-1的结果
循环开始处理第 i 个物品的瞬间：
`dp[0...V]` = 二维里 `dp[i-1][0...V]`（旧数据）
*/
// OneDim01 01背包一维滚动数组优化
// n:物品数量, V:背包容量
// w[]:物品重量, v[]:物品价值，下标从1开始对齐dp
// 返回最大价值
func OneDim01(n, V int, w, v []int) int {
	// dp[j]：容量j的最大价值
	// 初始就是 i=0 的情况：0个物品，全部价值0
	dp := make([]int, V+1)
	// 枚举物品
	for i := 1; i <= n; i++ {
		// ⚠️ 逆序！从V往下走到w[i]
		// j < w[i] 的位置：放不下，直接保留原值，等价 dp[i][j] = dp[i-1][j]
		for j := V; j >= w[i]; j-- {
			dp[j] = max(dp[j], dp[j-w[i]]+v[i])
		}
	}
	return dp[V]
}
